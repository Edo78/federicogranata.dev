const { DateTime } = require("luxon");
const path = require("node:path");
const fs = require("node:fs");
const syntaxHighlight = require("@11ty/eleventy-plugin-syntaxhighlight");
const pluginRss = require("@11ty/eleventy-plugin-rss").default;
const eleventyImage = require("@11ty/eleventy-img").default;
const { resolveSchema, VALID_SCHEMAS, buildJsonLdSchema } = require("./src/_data/helpers/schema.js");
const { isSafeUrl, validateSettings, validatePost } = require("./src/_data/helpers/validate.js");
const { topicSlug, topicUrl } = require("./src/_data/helpers/topics.js");
const { attachmentLinks } = require("./src/_data/helpers/attachments.js");

let _md; // shared markdown-it reference — assigned via amendLibrary below

// Utility: divide un array in chunk
function chunkArray(arr, size) {
  if (!arr.length) return [[]];
  return Array.from(
    { length: Math.ceil(arr.length / size) },
    (_, i) => arr.slice(i * size, i * size + size)
  );
}

function estimateReadingMinutes(value) {
  const text = String(value || "")
    .replace(/<[^>]*>/g, " ")
    .replace(/\s+/g, " ")
    .trim();
  const words = text ? text.split(" ").length : 0;
  return Math.max(1, Math.ceil(words / 220));
}

function effectiveDate(...values) {
  const dates = values
    .filter(Boolean)
    .map(value => value instanceof Date ? value : new Date(value))
    .filter(value => !Number.isNaN(value.valueOf()));
  if (!dates.length) return null;
  return new Date(Math.max(...dates.map(value => value.valueOf())));
}

function isDevelopment() {
  return process.env.ELEVENTY_ENV === "development";
}

module.exports = function (eleventyConfig) {
  // Read a fresh snapshot on each configuration reset, including CMS saves.
  const settings = JSON.parse(fs.readFileSync(path.join(__dirname, "src/_data/settings.json"), "utf8"));
  const { categorySlugs, categoryTopics, formatValues } = validateSettings(settings);

  function getVisiblePosts(collectionApi) {
    const posts = collectionApi.getFilteredByTag("post");
    posts.forEach((post) => validatePost(post.data, categorySlugs, formatValues, categoryTopics));
    return posts
      .filter((post) => isDevelopment() || post.data.published)
      .sort((a, b) => b.date - a.date);
  }

  // --- Plugins ---
  eleventyConfig.addPlugin(syntaxHighlight);
  eleventyConfig.addPlugin(pluginRss);

  // --- Passthrough Copy ---
  eleventyConfig.addPassthroughCopy({ "src/public": "/" });
  eleventyConfig.addPassthroughCopy({ "src/assets/files": "/files" });
  // Decap previews image fields via their public URL; keep originals available
  // alongside the optimized variants generated by Eleventy Image.
  eleventyConfig.addPassthroughCopy({ "src/assets/images": "/img" });

  // --- Filters ---
  // Date filters handle both JS Date objects and ISO strings (e.g., `updated` field)
  function toDateTime(dateObj) {
    const dateTime = typeof dateObj === "string"
      ? DateTime.fromISO(dateObj, { setZone: true })
      : DateTime.fromJSDate(dateObj);
    return dateTime.setZone(settings.site.timezone);
  }

  eleventyConfig.addFilter("readableDate", (dateObj) => {
    return toDateTime(dateObj).setLocale("it").toFormat("dd LLLL yyyy");
  });

  eleventyConfig.addFilter("isoDate", (dateObj) => {
    return toDateTime(dateObj).toISO();
  });

  eleventyConfig.addFilter("limit", (arr, count) => {
    return arr.slice(0, count);
  });

  eleventyConfig.addFilter("excludePost", (arr, post) => {
    return arr.filter(p => p.inputPath !== post.inputPath);
  });

  eleventyConfig.addFilter("readingTime", (value) => {
    const minutes = estimateReadingMinutes(value);
    return `${minutes} min`;
  });

  eleventyConfig.addFilter("latestUpdated", (posts) => {
    if (!posts || !posts.length) return null;
    return posts.reduce((latest, post) => {
      const candidate = effectiveDate(post.date, post.data.updated, post.data.lastVerified);
      return !latest || candidate > latest ? candidate : latest;
    }, null);
  });

  eleventyConfig.addFilter("sortByUpdated", (posts) => {
    return [...(posts || [])].sort((a, b) => {
      const aDate = effectiveDate(a.date, a.data.updated, a.data.lastVerified);
      const bDate = effectiveDate(b.date, b.data.updated, b.data.lastVerified);
      return bDate - aDate;
    });
  });

  eleventyConfig.addFilter("effectiveDate", (date, updated, lastVerified) => {
    return effectiveDate(date, updated, lastVerified);
  });

  eleventyConfig.addFilter("isNavActive", (pageUrl, itemUrl) => {
    if (!pageUrl || !itemUrl) return false;
    if (itemUrl === "/") return pageUrl === "/" || pageUrl.startsWith("/page/");
    return pageUrl === itemUrl || pageUrl.startsWith(itemUrl);
  });

  eleventyConfig.addFilter("navigationItems", (categories) => [
    { label: "Home", url: "/" },
    ...categories.map(category => ({ label: category.name, url: `/${category.slug}/` })),
    { label: "Chi sono", url: "/about-me/" },
  ]);

  eleventyConfig.addFilter("formatLabel", (format) => {
    return settings.formats?.find(item => item.value === format)?.label || "Nota";
  });

  eleventyConfig.addFilter("statusLabel", (status) => {
    return {
      current: "Corrente",
      evergreen: "Evergreen",
      archived: "Archivio",
      "needs-review": "Da rivedere",
    }[status] || "";
  });

  eleventyConfig.addFilter("relatedPosts", (posts, currentInputPath, category, tags, count = 2) => {
    const currentTags = new Set((tags || []).filter(tag => tag !== "post"));
    return (posts || [])
      .filter(post => post.inputPath !== currentInputPath)
      .map(post => {
        const sharedTopics = (post.data.tags || []).filter(tag => currentTags.has(tag)).length;
        const score = sharedTopics * 3 + (post.data.category === category ? 2 : 0);
        return { post, score };
      })
      .sort((a, b) => b.score - a.score || b.post.date - a.post.date)
      .slice(0, count)
      .map(item => item.post);
  });

  // Content format selects structured data; topics remain purely editorial.
  eleventyConfig.addFilter("resolveSchema", (format, category) => {
    return resolveSchema(format || "", category || "", settings);
  });

  // safeUrl: only allow relative paths and http/https URLs to prevent javascript: injection
  eleventyConfig.addFilter("safeUrl", (url) => {
    return isSafeUrl(url) ? String(url) : "";
  });

  eleventyConfig.addFilter("basename", (str) => {
    if (!str) return "";
    return String(str).replace(/\\/g, "/").split("/").filter(Boolean).pop() || str;
  });

  eleventyConfig.addFilter("attachmentLinks", attachmentLinks);

  // JSON strings are valid YAML scalars and preserve characters such as &.
  eleventyConfig.addFilter("yamlScalar", (value) => JSON.stringify(String(value || "")));

  eleventyConfig.addFilter("getCategoryData", (slug) => {
    return settings.categories.find(c => c.slug === slug) || null;
  });

  eleventyConfig.addFilter("topicUrl", (topic, category) => topicUrl(category, topic));

  eleventyConfig.addFilter("getCategoryTopics", (slug) => {
    return (settings.categories.find(category => category.slug === slug)?.tags || [])
      .map(topic => ({ name: topic.name, url: topicUrl(slug, topic.name) }));
  });

  eleventyConfig.addFilter("taxonomyJson", (categories) => {
    const taxonomy = {};
    (categories || []).forEach(cat => {
      taxonomy[cat.slug] = (cat.tags || []).map(t => t.name);
    });
    return JSON.stringify(taxonomy);
  });

  // --- Collections ---

  // All published posts in production; all posts in development.
  eleventyConfig.addCollection("posts", (collectionApi) => getVisiblePosts(collectionApi));

  // Multiple posts may stay pinned; archives feature the newest visible one
  // globally or within their category, by publication date.
  eleventyConfig.addCollection("pinnedPosts", (collectionApi) => {
    return getVisiblePosts(collectionApi)
      .filter((post) => post.data.pinned)
      .sort((a, b) => b.date - a.date);
  });

  // Home pages pre-chunked from the global post list so pagination size stays
  // centralized in settings.site.postsPerPage.
  eleventyConfig.addCollection("homePages", (collectionApi) => {
    const allPosts = getVisiblePosts(collectionApi);
    const pinnedPost = allPosts.find((post) => post.data.pinned) || null;
    const gridPosts = pinnedPost
      ? allPosts.filter((post) => post.inputPath !== pinnedPost.inputPath)
      : allPosts;
    const chunks = chunkArray(gridPosts, settings.site.postsPerPage);

    return chunks.map((posts, pageIndex) => ({
      posts,
      pageIndex,
      totalPages: chunks.length || 1,
      totalPosts: allPosts.length,
      pinnedPost,
    }));
  });

  // Posts grouped by category
  eleventyConfig.addCollection("postsByCategory", (collectionApi) => {
    const posts = getVisiblePosts(collectionApi);

    const grouped = {};
    settings.categories.forEach((cat) => {
      grouped[cat.slug] = posts.filter(p => p.data.category === cat.slug);
    });
    return grouped;
  });

  // Category pages for double pagination
  eleventyConfig.addCollection("categoryPages", (collectionApi) => {
    const allPosts = getVisiblePosts(collectionApi);
    const pages = [];

    settings.categories.forEach(category => {
      const catPosts = allPosts.filter(p => p.data.category === category.slug);
      const pinnedPost = catPosts.find(p => p.data.pinned) || null;
      const gridPosts = pinnedPost
        ? catPosts.filter(p => p.inputPath !== pinnedPost.inputPath)
        : catPosts;
      const chunks = chunkArray(gridPosts, settings.site.postsPerPage);

      chunks.forEach((chunk, index) => {
        pages.push({
          category,
          pinnedPost,
          pageIndex: index,
          totalPages: chunks.length || 1,
          totalPosts: catPosts.length,
          posts: chunk
        });
      });
    });

    return pages;
  });

  // Topic names are scoped to their category, including empty configured topics.
  eleventyConfig.addCollection("topicPages", (collectionApi) => {
    const allPosts = getVisiblePosts(collectionApi);
    return settings.categories.flatMap(category => (category.tags || []).flatMap(tag => {
      const topic = { name: tag.name, slug: topicSlug(tag.name), url: topicUrl(category.slug, tag.name) };
      const topicPosts = allPosts.filter(post => post.data.category === category.slug && post.data.tags.includes(tag.name));
      const pinnedPost = topicPosts.find(post => post.data.pinned) || null;
      const archivePosts = topicPosts.filter(post => post.inputPath !== pinnedPost?.inputPath);
      const chunks = chunkArray(archivePosts, settings.site.postsPerPage);
      return chunks.map((posts, pageIndex) => ({
        category,
        topic,
        pinnedPost,
        posts,
        pageIndex,
        totalPages: chunks.length,
        totalPosts: topicPosts.length,
      }));
    }));
  });

  // --- Image Shortcode ---
  const renderImage = async (src, alt, preset = "content", priority = false) => {
    if (!src) return "";
    const imageSource = src.startsWith("/img/")
      ? path.join(process.cwd(), "src/assets/images", path.basename(src))
      : src.startsWith("/src/")
        ? path.join(process.cwd(), src.slice(1))
        : src;
    const configuredWidths = {
      thumbnail: settings.site.images.thumbnail.width,
      header: settings.site.images.header.width,
      content: settings.site.images.content.width
    };
    const maxWidth = configuredWidths[preset] || configuredWidths.content;
    const widths = [Math.max(200, Math.round(maxWidth / 2)), maxWidth];
    const sizes = {
      thumbnail: "(min-width: 768px) 240px, calc(100vw - 2rem)",
      header: "(min-width: 768px) 720px, calc(100vw - 3rem)",
      content: "(min-width: 768px) 720px, calc(100vw - 3rem)",
    };
    const imgAttributes = {
      alt: alt || "",
      loading: priority ? "eager" : "lazy",
      decoding: "async",
      sizes: sizes[preset] || sizes.content,
    };
    if (priority) imgAttributes.fetchpriority = "high";

    return eleventyImage(imageSource, {
      widths,
      formats: ["avif", "webp", "jpeg"],
      outputDir: "./_site/img/",
      urlPath: "/img/",
      returnType: "html",
      htmlOptions: {
        imgAttributes
      }
    });
  };

  eleventyConfig.addShortcode("image", renderImage);

  eleventyConfig.addShortcode("postCard", async function (post, headingLevel = 3) {
    const category = settings.categories.find(cat => cat.slug === post.data.category);
    const tags = (post.data.tags || []).filter(tag => tag !== "post");
    const cover = post.data.cover
      ? await renderImage(post.data.cover, "", "thumbnail")
      : "";
    const escape = value => String(value || "")
      .replaceAll("&", "&amp;")
      .replaceAll("<", "&lt;")
      .replaceAll(">", "&gt;")
      .replaceAll('"', "&quot;");
    const dateIso = post.date.toISOString();
    const dateLabel = new Intl.DateTimeFormat("it-IT", {
      day: "2-digit",
      month: "long",
      year: "numeric",
      timeZone: settings.site.timezone,
    }).format(post.date);
    const readingTime = `${estimateReadingMinutes(post.templateContent || post.data.description)} min`;
    const format = settings.formats?.find(item => item.value === post.data.format)?.label || "Nota";

    const heading = Number(headingLevel) === 2 ? 2 : 3;

    return `<article class="story-row card-surface${cover ? "" : " story-row-no-media"}">
  ${cover ? `<div class="story-media">${cover}</div>` : ""}
  <div class="story-copy">
    <div class="card-meta">
      ${category ? `<a href="/${escape(category.slug)}/" class="meta-link">${escape(category.name)}</a><span class="meta-dot">&middot;</span>` : ""}
      <time datetime="${escape(dateIso)}">${escape(dateLabel)}</time>
      <span class="meta-dot" aria-hidden="true">&middot;</span><span>${escape(readingTime)}</span>
    </div>
    <p class="eyebrow mt-4">${escape(format)}</p>
    <h${heading} class="mt-2 display-title text-2xl sm:text-[2rem] text-text-strong"><a href="${escape(post.url)}" class="story-link card-link">${escape(post.data.title)}</a></h${heading}>
    <p class="mt-3 text-sm sm:text-base leading-relaxed text-text-soft">${escape(post.data.description)}</p>
    <div class="story-footer mt-5 flex flex-wrap items-end justify-between gap-4">
      ${tags.length ? `<div class="flex flex-wrap gap-x-3 gap-y-1">${tags.map(tag => `<a href="${escape(topicUrl(post.data.category, tag))}" class="topic-label">#${escape(tag)}</a>`).join("")}</div>` : "<span></span>"}
      <span class="read-more" aria-hidden="true">Apri nota &rarr;</span>
    </div>
  </div>
</article>`;
  });

  // --- jsonld shortcode ---
  // Generates a <script type="application/ld+json"> block entirely in JS so
  // Nunjucks autoescape never touches the serialized values.
  // Eleventy wraps shortcode output in SafeString automatically, so it is
  // output verbatim in the template.
  eleventyConfig.addShortcode("jsonld", function () {
    const ctx = this.ctx;
    const siteUrl = settings.site.url;
    const authorName = settings.site.author.name;
    const resolved = resolveSchema(ctx.format || "", ctx.category || "", settings);
    const schemaType = VALID_SCHEMAS.has(resolved) ? resolved : "BlogPosting";

    const schema = {
      "@context": "https://schema.org",
      ...buildJsonLdSchema({ schemaType, siteUrl, authorName, ctx }),
    };

    const json = JSON.stringify(schema, null, 2).replace(/<\//g, "<\\/");
    return `<script type="application/ld+json">\n${json}\n</script>`;
  });

  // --- Markdown Image Override ---
  // Ensure lazy loading and async decoding on all Markdown images.
  // escAttr prevents XSS by HTML-encoding characters that break attribute context.
  function escAttr(str) {
    return String(str)
      .replace(/&/g, "&amp;")
      .replace(/"/g, "&quot;")
      .replace(/'/g, "&#39;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;");
  }

  eleventyConfig.amendLibrary("md", (mdLib) => {
    _md = mdLib; // capture Eleventy's shared markdown-it instance
    mdLib.set({ html: false, linkify: false });
    mdLib.renderer.rules.image = function (tokens, idx) {
      const token = tokens[idx];
      const src = escAttr(token.attrGet("src") || "");
      const alt = escAttr(token.content || "");
      return `<img src="${src}" alt="${alt}" loading="lazy" decoding="async">`;
    };
  });

  // Raw HTML is disabled on the shared Markdown renderer.
  eleventyConfig.addFilter("markdownify", (str) => {
    if (!str || !_md) return str || "";
    return _md.render(String(str));
  });

  // --- Watch Targets ---
  eleventyConfig.addWatchTarget("tailwind.css");
  // Collections and validation capture settings when configuration is loaded.
  // Reload them too when the CMS changes categories, topics or formats.
  eleventyConfig.addWatchTarget("./src/_data/settings.json", { resetConfig: true });

  return {
    dir: {
      input: "src",
      includes: "_includes",
      data: "_data",
      output: "_site"
    },
    templateFormats: ["njk", "md", "html"],
    markdownTemplateEngine: "njk",
    htmlTemplateEngine: "njk"
  };
};
